# Copies the Faust-generated DSP class (mydsp) out of plugin/pregen/FaustPlugin.cpp
# into mobile/core/bbba_faust_generated.h, without the DPF plugin code around it.
# `make pregen` runs it after regenerating the plugin sources.
#
#   mobile/tools/extract_faust.sh           rewrite the header
#   mobile/tools/extract_faust.sh --check   exit 1 if the header is out of date
set -eu

root=$(cd "$(dirname "$0")/../.." && pwd)
src="$root/plugin/pregen/FaustPlugin.cpp"
dst="$root/mobile/core/bbba_faust_generated.h"

tmp=$(mktemp)
trap 'rm -f "$tmp"' EXIT

# The class sits between the `#if defined(__GNUC__)` / diagnostic push block and the
# matching diagnostic pop block; both are emitted once, around the class only.
{
    echo '// Extracted from plugin/pregen/FaustPlugin.cpp by mobile/tools/extract_faust.sh.'
    echo '// Generated by the Faust compiler; do not edit by hand.'
    echo '// SPDX-License-Identifier: GPL-3.0-or-later   (Faust DSP by Klaus Scheuermann)'
    echo '#pragma once'
    echo
    awk '
        !on && /pragma GCC diagnostic push/ { on = 1; print prev }
        on { print }
        on && /pragma GCC diagnostic pop/ { closing = 1; next }
        closing && /^#endif/ { found = 1; exit }
        { prev = $0 }
        END { if (!found) exit 1 }
    ' "$src"
} > "$tmp" || { echo "extract_faust: Faust class not found in $src" >&2; exit 1; }

if [ "${1:-}" = "--check" ]; then
    if cmp -s "$tmp" "$dst"; then
        exit 0
    fi
    echo "extract_faust: $dst is out of date, run mobile/tools/extract_faust.sh" >&2
    exit 1
fi

cp "$tmp" "$dst"
